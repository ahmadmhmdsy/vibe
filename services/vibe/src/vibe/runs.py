# services/vibe/src/vibe/runs.py
"""Registry of in-flight agent runs, one per session.

The chat route streams a run to completion inside the POST. Without a handle
on that work there is nothing for an abort request to cancel -- the frontend's
Stop button only flipped a local flag while the run kept going.

A run is claimed per *owner and* session, not per session id alone. The id is
generated by the store, so two owners are free to hold the same one; keying on
the id alone would let the second owner's request find the first owner's handle,
believe the session is busy, and cancel work that was never theirs.
"""
from __future__ import annotations

import asyncio
from dataclasses import dataclass, field

from vibe.auth import LOOPBACK_OWNER_ID


@dataclass(frozen=True, slots=True)
class SessionKey:
    """Who a session-level resource belongs to, and which session it is.

    A value object rather than a joined string so the pair cannot be passed in
    the wrong order, and rather than a tuple so the two halves stay named. The
    owner is never defaulted here: every construction names both halves.
    """

    owner_id: str
    session_id: str

    def __str__(self) -> str:
        return f"{self.owner_id}/{self.session_id}"


@dataclass
class RunHandle:
    session_id: str
    task: asyncio.Task | None = None
    aborted: bool = False
    _abort: asyncio.Event = field(default_factory=asyncio.Event)

    def request_abort(self) -> bool:
        """Cancel the run. True if a live run was actually stopped."""
        if self.aborted:
            return False
        self.aborted = True
        self._abort.set()
        if self.task is not None and not self.task.done():
            self.task.cancel()
            return True
        return False

    @property
    def abort_requested(self) -> bool:
        return self.aborted


class RunRegistry:
    """Which run is in flight, keyed by (owner, session).

    Every method takes the owner as a keyword with the loopback default, so a
    caller that has a principal passes it and a local script or test that does
    not gets the single-user behaviour the app ships with.
    """

    def __init__(self):
        self._runs: dict[SessionKey, RunHandle] = {}

    @staticmethod
    def key(session_id: str, owner_id: str = LOOPBACK_OWNER_ID) -> SessionKey:
        return SessionKey(owner_id=owner_id, session_id=session_id)

    def get(self, session_id: str, *, owner_id: str = LOOPBACK_OWNER_ID) -> RunHandle | None:
        return self._runs.get(self.key(session_id, owner_id))

    def is_running(self, session_id: str, *, owner_id: str = LOOPBACK_OWNER_ID) -> bool:
        handle = self._runs.get(self.key(session_id, owner_id))
        return handle is not None and not handle.aborted

    def start(self, session_id: str, *, owner_id: str = LOOPBACK_OWNER_ID) -> RunHandle:
        handle = RunHandle(session_id=session_id)
        self._runs[self.key(session_id, owner_id)] = handle
        return handle

    def try_start(
        self, session_id: str, *, owner_id: str = LOOPBACK_OWNER_ID
    ) -> RunHandle | None:
        """Claim the session's run slot, or None when it is already taken.

        Callers must claim before their first await. A check separated from the
        claim by an await lets two concurrent requests both pass the check and
        both run the agent. An aborted handle still owns its slot until finish,
        because the task it wraps may still be writing events.
        """
        key = self.key(session_id, owner_id)
        if key in self._runs:
            return None
        return self.start(session_id, owner_id=owner_id)

    def finish(
        self, session_id: str, handle: RunHandle, *, owner_id: str = LOOPBACK_OWNER_ID
    ) -> None:
        key = self.key(session_id, owner_id)
        if self._runs.get(key) is handle:
            self._runs.pop(key, None)

    def abort_all(self) -> int:
        """Abort every run still in flight; returns how many were live.

        Shutdown used to just drop the process, so a run cancelled by Ctrl+C
        never got to write its turn/aborted event -- and the next start found a
        session that looked permanently busy.
        """
        stopped = 0
        for handle in list(self._runs.values()):
            if handle.request_abort():
                stopped += 1
        return stopped

    def abort(self, session_id: str, *, owner_id: str = LOOPBACK_OWNER_ID) -> bool:
        handle = self._runs.get(self.key(session_id, owner_id))
        if handle is None:
            return False
        return handle.request_abort()
